const MARKS: Record<string, (c: number) => [number, number][]> = {
  "́": (c) => [[c + 1, 0], [c, 1]],
  "̀": (c) => [[c - 1, 0], [c, 1]],
  "̂": (c) => [[c - 1, 1], [c, 0], [c + 1, 1]],
  "̃": (c) => [[c - 1, 1], [c, 0], [c + 1, 1], [c + 2, 0]],
  "̈": (c) => [[c - 1, 1], [c + 1, 1]],
};

export const GLYPH_TOP = 2;

const SPACE: Glyph = { width: 3, cells: [] };

export const glyphFor = (char: string): Glyph => {
  if (char === " ") return SPACE;
  const [base, ...marks] = Array.from(char.normalize("NFD"));
  const bitmap = UPPER[base] ?? UPPER["?"];
  const width = Math.max(...bitmap.map((row) => row.length));
  const cells: [number, number][] = [];
  bitmap.forEach((row, y) => {
    Array.from(row).forEach((dot, x) => {
      if (dot === "#") cells.push([x, y + GLYPH_TOP]);
    });
  });
  const centre = Math.floor((width - 1) / 2);
  marks.forEach((mark) => {
    MARKS[mark]?.(centre).forEach(([x, y]) => cells.push([x, y]));
  });
  return { width, cells };
};
